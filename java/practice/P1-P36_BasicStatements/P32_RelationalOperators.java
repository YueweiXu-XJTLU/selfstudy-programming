package S1_BasicStatements;

public class P32_RelationalOperators {
    public static void main(String[] args) {
        //Relational Operator 关系运算符
/*
        == equal to
        != not equal to
        > greater than
        > greater than
        < less than
        >= greater than or equal to
        <= less than or equal to
*/
/*
        output "true" if true
        output "false" if false
*/

        int a = 10;
        int b = 20;
        System.out.println(a == b);//Relational Operator: ==
        System.out.println(a = b); //Assignment Operator: = //a = b; System.out.println(a)


    }
}
